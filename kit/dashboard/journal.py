RUNNING, HALTED, FINISHED = 'running', 'halted', 'finished'

# Work item states shown on the timeline.
AT_EXECUTOR = 'executor'   # delegated, the executor has not returned (no inspection yet)
IN_REVIEW = 'review'       # inspected, no review recorded yet
ACCEPTED = 'accepted'      # the latest attempt was accepted
REWORK = 'rework'          # the latest attempt was sent back and no new attempt started yet
FAILED = 'failed'          # the executor returned no work and changed no files (error, rate limit)

NOT_GREEN = {CATEGORY_FAILED, CATEGORY_INCOMPLETE, CATEGORY_NO_RESULT, CATEGORY_TIMEOUT}


def parse_event(line: str, number: int) -> dict:
    """Parse one journal line into an event, because the journal is a JSONL file. The line number is for error messages.
    Returns the dict.
    Raises:
        ValueError: invalid JSON or wrong shape; the message contains "line <number>".
    Legacy 'piece' is read as 'work_item'; conflicting names are rejected.
    """
    try:
        resulting_dict = json.loads(line)
        if not isinstance(resulting_dict, dict):
            raise ValueError(f'line {number}: not a JSON a dictionary')
        if (not isinstance(resulting_dict.get('kind'), str) or not valid_number(resulting_dict.get('at'))):
            raise ValueError(f'line {number}: missing or invalid "kind" or "at"')
    except json.JSONDecodeError as error:
        raise ValueError(f'line {number}: invalid JSON') from error
    try:
        return normalize_work_item(resulting_dict)
    except ValueError as error:
        raise ValueError(f'line {number}: {error}') from error


def read_events(path: Path) -> list[dict]:
    """Returns all the events of a journal file, in file order.

    - Missing file -> []  the task folder may exist before the first event.
    - Blank lines are skipped.
    - The last non-blank line may be cut in half by a writer that is still appending:
      if it is not valid JSON, it is ignored. 
      Any earlier bad line raises ValueError
      through parse_event, with its 1-based line number
    - Read as UTF-8 text; a BOM at the start is accepted.
    - Valid JSON with the wrong event shape raises ValueError even on the last line.
    """
    resulting_events = []
    path = Path(path)
    if not path.exists():
        return []
    # bom will be removed by 'utf-8-sig' encoding, so the first line will be valid JSON.
    # bom means "byte order mark" (U+FEFF) at the start of a UTF-8 file.
    # we don't need it, but some editors add it automatically.
    text = path.read_text(encoding='utf-8-sig')
    event_lines = text.splitlines()
    
    while event_lines and event_lines[-1].strip() == '':
        event_lines.pop()

    for line_number, line in enumerate(event_lines, start=1):
        if line.strip() == '':
            continue

        try:
            event = parse_event(line, line_number)
        except ValueError as error:
            broken_line = isinstance(error.__cause__, json.JSONDecodeError) and line_number == len(event_lines)
            if broken_line:
                continue  # skip the last broken line, but raise for any earlier broken line
            raise

        resulting_events.append(event)
    return resulting_events


