"""Read a task journal (.metrics/<task>/events.jsonl)/ convert it into dashboard views.

The journal will be generated by kit/task_metrics.py 
while a task runs, so every reader here must count on a writer that is working.
Pure (for my unit tests) functions take the list of events; only
read_events touches the disk.

Events I created before (journal.KNOWN_EVENT_TYPES in kit/journal.py): start, delegation, inspection, review, test,
halt, resume, finish. 
Every event has kind, at Unix seconds and "event_id".
inspection/review are related to their delegation through "delegation_id".

I learn and implement (2026-10-13) next functions in order:
parse_event -> read_events -> console.main,

"""
from __future__ import annotations
import json
from pathlib import Path
# .. means "kit" package, one level up from this module.
from ..task_metrics import is_halted, normalize_work_item, valid_number

RUNNING, HALTED, FINISHED = 'running', 'halted', 'finished'


def parse_event(line: str, number: int) -> dict:
    """Parse one journal line into an event, because the journal is a JSONL file. The line number is for error messages.
    Returns the dict.
    Raises:
        ValueError: invalid JSON or wrong shape; the message contains "line <number>".
    Legacy 'piece' is read as 'work_item'; conflicting names are rejected.
    """
    try:
        resulting_dict = json.loads(line)
        if not isinstance(resulting_dict, dict):
            raise ValueError(f'line {number}: not a JSON a dictionary')
        if (not isinstance(resulting_dict.get('kind'), str) or not valid_number(resulting_dict.get('at'))):
            raise ValueError(f'line {number}: missing or invalid "kind" or "at"')
    except json.JSONDecodeError as error:
        raise ValueError(f'line {number}: invalid JSON') from error
    try:
        return normalize_work_item(resulting_dict)
    except ValueError as error:
        raise ValueError(f'line {number}: {error}') from error


def read_events(path: Path) -> list[dict]:
    """Returns all the events of a journal file, in file order.

    - Missing file -> []  the task folder may exist before the first event.
    - Blank lines are skipped.
    - The last non-blank line may be cut in half by a writer that is still appending:
      if it is not valid JSON, it is ignored. 
      Any earlier bad line raises ValueError
      through parse_event, with its 1-based line number
    - Read as UTF-8 text; a BOM at the start is accepted.
    - Valid JSON with the wrong event shape raises ValueError even on the last line.
    """
    resulting_events = []
    path = Path(path)
    if not path.exists():
        return []
    # bom will be removed by 'utf-8-sig' encoding, so the first line will be valid JSON.
    # bom means "byte order mark" (U+FEFF) at the start of a UTF-8 file.
    # we don't need it, but some editors add it automatically.
    text = path.read_text(encoding='utf-8-sig')
    event_lines = text.splitlines()
    
    while event_lines and event_lines[-1].strip() == '':
        event_lines.pop()

    for line_number, line in enumerate(event_lines, start=1):
        if line.strip() == '':
            continue

        try:
            event = parse_event(line, line_number)
        except ValueError as error:
            broken_line = isinstance(error.__cause__, json.JSONDecodeError) and line_number == len(event_lines)
            if broken_line:
                continue  # skip the last broken line, but raise for any earlier broken line
            raise

        resulting_events.append(event)
    return resulting_events


def task_status(events: list[dict]) -> str:
    """Returns FINISHED if any finish event exists; otherwise HALTED if task_metrics.is_halted(events)
    returns an event; otherwise RUNNING.
    Raises:
        ValueError: events is empty.
    """
    if not events:
        raise ValueError('task_status: empty events list')
    if any(e.get('kind') == 'finish' for e in events):
        return FINISHED
    # I checked it only after the finish check, because is_halted may return a halt event even after a finish.
    if is_halted(events) is not None:
        return HALTED
    return RUNNING


def test_runs(events: list[dict]) -> list[dict]:
    """Every test event as a uniform row, in journal order.
    Row: at, scope (default "full"), phase (default "work"), status, category,
    tests, failures, errors, skipped, duration (from "duration_seconds").
    A counter missing from the event stays None: unknown is not zero.

    Note to remind aim to me: it doesn't run tests, it just reads the journal and gathers the test events.
    The executor runs tests and writes the journal.
    """
    resulting_output = []

    if not events:
        return resulting_output

    for event in events:
        # pass means do nothing; it is a placeholder for the next steps.
        if event.get('kind') == 'test':
            test_row = {
                'at': event.get('at'),
                'scope': event.get('scope', 'full'),
                'phase': event.get('phase', 'work'),
                'status': event.get('status'),
                'category': event.get('category'),
                'tests': event.get('tests'),
                'failures': event.get('failures'),
                'errors': event.get('errors'),
                'skipped': event.get('skipped'),
                'duration': event.get('duration_seconds')
            }
            resulting_output.append(test_row)
    return resulting_output


def brief_summary(events: list[dict]) -> dict:
    """Small task header for the runtime page; no work-item history or guard counters.

    Requires a non-empty list whose first event is start; otherwise raises ValueError.
    Returns exactly these keys:
        title: first event title, or "Untitled task" when missing
        status: task_status(events)
        event_count: len(events), including baseline events
        last_event_at: at of the last event, in file order
        work_runs: number of test_runs rows whose phase is not baseline
        green_work_runs: number of those rows whose status is passed
        reworks: number of review events with result rework
        executor_failures: number of review events with result failed

    A failed executor attempt is not a rework. This is a small view of the same
    journal, not a replacement for the final task_metrics report.
    """
    event_count = len(events)
    if not events or events[0].get('kind') != 'start':
        raise ValueError('brief_summary: events must be non-empty and start with a "start" event')

    if len(events) == 1:
        return {
            'title': events[0].get('title', 'Untitled task'),
            'status': task_status(events),
            'event_count': 1,
            'last_event_at': events[0].get('at'),
            'work_runs': 0,
            'green_work_runs': 0,
            'reworks': 0,
            'executor_failures': 0
        }

    last_event_at = events[-1].get('at')
    # remind me: work_runs is the number of test events
    # whose phase is not baseline, and green_work_runs is the number of those whose status is passed.
    # baseline tests we do when we want to check the executor's environment and code itself.
    # it goes right after the start event, and it is not counted in work_runs or green_work_runs.
    # so these kinds of tests are not passed from the very beginning, but they are not failures either. They are just a baseline.
    work_runs = sum(1 for e in events if e.get('kind') == 'test' and e.get('phase') != 'baseline')
    green_work_runs = sum(1 for e in events if e.get('kind') == 'test' and e.get('phase') != 'baseline' and e.get('status') == 'passed')
    reworks = sum(1 for e in events if e.get('kind') == 'review' and e.get('result') == 'rework')
    executor_failures = sum(1 for e in events if e.get('kind') == 'review' and e.get('result') == 'failed')

    return {
        'title': events[0].get('title', 'Untitled task'),
        'status': task_status(events),
        'event_count': event_count,
        'last_event_at': last_event_at,
        'work_runs': work_runs,
        'green_work_runs': green_work_runs,
        'reworks': reworks,
        'executor_failures': executor_failures
    }
