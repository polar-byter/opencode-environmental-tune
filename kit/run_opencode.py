"""Start OpenCode with both executors bound to an already loaded LM Studio instance."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')

try:
    from .check_env import strip_jsonc
    from .lmstudio_models import base_url, configured_model, loaded_models, select_model
except ImportError:
    from check_env import strip_jsonc
    from lmstudio_models import base_url, configured_model, loaded_models, select_model

HEADER = '// Generated by kit/run_opencode.py. Local model selection; do not edit.\n'
ALIAS = 'loaded-executor'


def find_opencode(command: str) -> str:
    """Use the native CLI so Windows batch quoting cannot alter forwarded arguments."""
    executable = shutil.which(command)
    if command == 'opencode' and (not executable or Path(executable).suffix.lower() in ('.cmd', '.bat')):
        installed = Path(os.environ.get('LOCALAPPDATA', '')) / 'Programs/@opencodedesktop/resources/opencode-cli.exe'
        if installed.is_file():
            executable = str(installed)
    if not executable:
        raise ValueError('OpenCode CLI not found. Install it or pass --opencode with its path.')
    if Path(executable).suffix.lower() in ('.cmd', '.bat'):
        raise ValueError('Pass --opencode with the native opencode.exe/opencode-cli.exe path; .cmd/.bat wrappers are not supported.')
    return executable


def prepare(root: Path, explicit: str | None = None):
    """Write only our local overlay, preserving the source config and agent permissions."""
    config = json.loads(strip_jsonc((root / 'opencode.jsonc').read_text(encoding='utf-8-sig')))
    for name in ('executor', 'executor-fast'):
        agent = config.get('agents', {}).get(name, {})
        if not isinstance(agent.get('model'), str) or not agent['model'].startswith('lmstudio/'):
            raise ValueError(f'{name} must be configured as an LM Studio agent')
    directory = root / '.opencode'
    overlay = directory / 'opencode.jsonc'
    if (directory / 'opencode.json').exists():
        raise ValueError('Existing .opencode/opencode.json: move its settings into the project config before using this launcher')
    if overlay.exists() and not overlay.read_text(encoding='utf-8').startswith(HEADER):
        raise ValueError('Existing .opencode/opencode.jsonc belongs to you; it will not be overwritten. Move its settings into the project config first.')
    model = select_model(loaded_models(base_url(config)), configured_model(config), explicit)
    patch = {
        'providers': {'lmstudio': {'models': {ALIAS: {'modelID': model.id, 'name': model.name + ' (already loaded)'}}}},
        'agents': {name: {'model': 'lmstudio/' + ALIAS} for name in ('executor', 'executor-fast')},
    }
    directory.mkdir(exist_ok=True)
    temporary = directory / 'opencode.jsonc.tmp'
    temporary.write_text(HEADER + json.dumps(patch, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    temporary.replace(overlay)
    return model


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--model', help='loaded LM Studio instance ID (required only for ambiguous selection)')
    parser.add_argument('--prepare-only', action='store_true', help='prepare the config before opening the project in the desktop app')
    parser.add_argument('--reload', action='store_true', help='with --prepare-only: reload the current background OpenCode service')
    parser.add_argument('--opencode', default='opencode', help='OpenCode executable or command on PATH')
    parser.add_argument('arguments', nargs=argparse.REMAINDER, help='OpenCode arguments after --')
    args = parser.parse_args(argv)
    if args.reload and not args.prepare_only:
        parser.error('--reload requires --prepare-only')
    root = Path.cwd()
    try:
        executable = None
        if not args.prepare_only or args.reload:
            executable = find_opencode(args.opencode)
        model = prepare(root, args.model)
        print(f'Already loaded: {model.name}\nInstance: {model.id}\nBoth executors use this instance; load settings are unchanged.', flush=True)
        if args.prepare_only:
            if args.reload:
                return subprocess.call([executable, 'reload'], cwd=root)
            print('Now open or reopen this project in OpenCode. Run preparation again after changing the loaded model.')
            return 0
        arguments = args.arguments[1:] if args.arguments[:1] == ['--'] else args.arguments
        if arguments[:1] == ['run'] and not any(a == '--standalone' or a == '--server' or a.startswith('--server=') for a in arguments):
            arguments = ['run', '--standalone', *arguments[1:]]
        # Expose launch facts to the agent so a private session does not reload another server.
        environment = os.environ.copy()
        environment['OPENCODE_KIT_ROOT'] = str(root.resolve())
        environment['OPENCODE_KIT_INSTANCE'] = model.id
        environment['OPENCODE_KIT_SERVER_MODE'] = 'standalone' if '--standalone' in arguments else 'shared'
        # Pass an argument list directly to the native CLI, without a shell.
        return subprocess.call([executable, *arguments], cwd=root, env=environment)
    except (ValueError, OSError) as error:
        print(f'ERROR: {error}', file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        return 130


if __name__ == '__main__':
    raise SystemExit(main())
